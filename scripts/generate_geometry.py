"""Check frozen publication geometry against an in-memory regeneration.

Canonical geometry files are publication artifacts and are not overwritten by
this script. Run the check only in the pinned environment documented in
``requirements-publication.txt``.
"""

from __future__ import annotations

import argparse
from hashlib import sha256
import importlib.metadata
from io import StringIO
from pathlib import Path
import platform
import tomllib

import pandas as pd

from superinformation.geometry import GeometryResult, analyze_geometry


ROOT = Path(__file__).resolve().parents[1]
REFERENCE = ROOT / "tests" / "fixtures" / "reference" / "superinformation_values.csv"
OUT = ROOT / "results" / "geometry"
MANIFEST = OUT / "GEOMETRY_MANIFEST.toml"

EXPECTED_PYTHON = "3.11.9"
EXPECTED_PACKAGES = {
    "numpy": "2.0.2",
    "scipy": "1.16.3",
    "scikit-learn": "1.6.1",
    "numba": "0.60.0",
    "llvmlite": "0.43.0",
    "pynndescent": "0.5.13",
    "umap-learn": "0.5.11",
    "joblib": "1.4.2",
}


class GeometryCheckError(RuntimeError):
    """Raised when frozen geometry differs from a validated regeneration."""


def _csv_bytes(frame: pd.DataFrame, **kwargs: object) -> bytes:
    buffer = StringIO(newline="")
    frame.to_csv(buffer, **kwargs)
    return buffer.getvalue().encode("utf-8")


def _regenerated_outputs(result: GeometryResult) -> dict[str, bytes]:
    """Serialize deterministic numerical outputs without writing to disk."""
    linkage = pd.DataFrame(
        result.linkage_matrix,
        columns=["left", "right", "distance", "cluster_size"],
    )
    order = pd.DataFrame({"dendrogram_order": result.dendrogram_order})
    return {
        "feature_level_si_matrix.csv": _csv_bytes(result.matrix),
        "pca_coordinates.csv": _csv_bytes(result.pca_coordinates),
        "pca_variance.csv": _csv_bytes(result.pca_variance, index=False),
        "umap_coordinates.csv": _csv_bytes(result.umap_coordinates),
        "clustering_linkage.csv": _csv_bytes(linkage, index=False),
        "clustering_distance.csv": _csv_bytes(result.distance_matrix),
        "cluster_assignments.csv": _csv_bytes(result.cluster_assignments, index=False),
        "cluster_composition.csv": _csv_bytes(result.cluster_composition, index=False),
        "dendrogram_order.csv": _csv_bytes(order, index=False),
    }


def _validate_environment() -> None:
    actual_python = platform.python_version()
    problems = []
    if actual_python != EXPECTED_PYTHON:
        problems.append(f"Python {actual_python} (expected {EXPECTED_PYTHON})")
    for distribution, expected in EXPECTED_PACKAGES.items():
        try:
            actual = importlib.metadata.version(distribution)
        except importlib.metadata.PackageNotFoundError:
            problems.append(f"{distribution} is not installed (expected {expected})")
        else:
            if actual != expected:
                problems.append(f"{distribution} {actual} (expected {expected})")
    if problems:
        details = "\n  - ".join(problems)
        raise GeometryCheckError(
            "Geometry regeneration requires the exact pinned publication environment:\n"
            f"  - {details}\n"
            "Install requirements-publication.txt under Python 3.11.9."
        )


def _compare_frozen_outputs(generated: dict[str, bytes], output_dir: Path) -> None:
    mismatches = []
    for name, regenerated in generated.items():
        frozen = output_dir / name
        if not frozen.is_file():
            mismatches.append(f"missing frozen file: {name}")
        elif frozen.read_bytes() != regenerated:
            mismatches.append(f"regenerated bytes differ: {name}")
    if mismatches:
        raise GeometryCheckError("\n".join(mismatches))


def _validate_manifest_hashes(output_dir: Path, manifest_path: Path) -> None:
    manifest = tomllib.loads(manifest_path.read_text(encoding="utf-8"))
    mismatches = []
    for name, expected in manifest["files"].items():
        path = output_dir / name
        if not path.is_file():
            mismatches.append(f"manifest file missing: {name}")
        elif sha256(path.read_bytes()).hexdigest() != expected:
            mismatches.append(f"manifest hash differs: {name}")
    if mismatches:
        raise GeometryCheckError("\n".join(mismatches))


def run_check(
    reference: Path = REFERENCE,
    output_dir: Path = OUT,
    manifest_path: Path = MANIFEST,
) -> None:
    """Regenerate in memory, compare with frozen files, and write nothing."""
    _validate_environment()
    result = analyze_geometry(pd.read_csv(reference))
    _compare_frozen_outputs(_regenerated_outputs(result), output_dir)
    _validate_manifest_hashes(output_dir, manifest_path)

    manifest = tomllib.loads(manifest_path.read_text(encoding="utf-8"))
    actual_input = sha256(reference.read_bytes()).hexdigest()
    if actual_input != manifest["geometry"]["input_sha256"]:
        raise GeometryCheckError("reference input hash differs from GEOMETRY_MANIFEST.toml")


def main() -> None:
    parser = argparse.ArgumentParser(description=__doc__)
    parser.add_argument(
        "--check",
        action="store_true",
        help="regenerate in memory and compare with frozen canonical files",
    )
    args = parser.parse_args()
    if not args.check:
        parser.error("only non-writing --check mode is supported for frozen publication outputs")
    run_check()
    print("Frozen geometry matches the in-memory regeneration and manifest hashes.")


if __name__ == "__main__":
    main()
